from sim3 import *
m5,h1=load()
print('=== 組: 主=4h po + 1時間 ord  (土台 CHK3 ADD20 MAX14 CHB22)')
print('--- 1時間の見方'); row('1時間=po', prep3(m5,h1,H1='po'))
print('--- 網の倍率 CHK(4h ATR)')
for k in (2,2.5,3,3.5,4): row(f'CHK={k}', prep3(m5,h1,H1='ord',CHK=k))
m=prep3(m5,h1,H1='ord')
print('--- 足しの間 ADDSTEP')
for a in (10,15,20,30,40): row(f'ADD={a}', m, ADDSTEP=a)
print('--- 最大発数 MAXPOS')
for p in (8,14,20,28): row(f'MAX={p}', m, MAXPOS=p)
print('--- 網の足 ATR')
for t in ('1h','1D'): row(f'ATR足={t} CHK3', prep3(m5,h1,H1='ord',ATRTF=t))
print('--- 打ち直しの間 COOL')
for c in (0,12,-1): row(f'COOL={c}', m, COOL=c)
print('--- スプレッド1.0'); row('spr1.0', m, 1.0)
